"""`docs/reference/errors.md` is generated from vibey's error catalog.

    python scripts/error_catalog.py render   # rewrite the page's GENERATED block
    python scripts/error_catalog.py check    # exit 1 if the page is out of step with the catalog

The catalog (`src/vibey/cli/error_codes.toml`, declared in `scripts/error_catalog.toml`) is the
one source: `Error:` output names a code from it, `vibey explain` prints its entry, and this
page lists the same entries, so the three cannot drift apart. `check` is the check that says
out loud when the page was not regenerated (sub-doctrine 12.e).
"""

from __future__ import annotations

import argparse
import re
import sys
import tomllib
from collections.abc import Sequence
from pathlib import Path

try:
    from scripts.interfaces.error_catalog_interface import ErrorPageInterface
except ModuleNotFoundError:  # Direct execution keeps the script directory on sys.path.
    from interfaces.error_catalog_interface import (  # type: ignore[import-not-found,no-redef]
        ErrorPageInterface,
    )

from vibey.cli.error_catalog import ErrorCatalog
from vibey.cli.interfaces.error_catalog_interface import ErrorCatalogInterface, ErrorEntry

SCRIPT = "scripts/error_catalog.py"
DEFAULT_CONFIG = "scripts/error_catalog.toml"
REPO = Path(__file__).resolve().parents[1]


class ErrorPage(ErrorPageInterface):
    """Implements `ErrorPageInterface` for one named GENERATED block."""

    def __init__(self, name: str) -> None:
        self._begin = f"<!-- BEGIN GENERATED {name} — regenerated by {SCRIPT} -->"
        self._end = f"<!-- END GENERATED {name} -->"
        self._pattern = re.compile(
            re.escape(self._begin) + r".*?" + re.escape(self._end), re.DOTALL
        )

    def block(self, catalog: ErrorCatalogInterface) -> str:
        rows = [
            "| Code | Error | What it means | What to do |",
            "|---|---|---|---|",
        ]
        rows += [self._row(entry) for entry in catalog.entries() if entry.code]
        return "\n".join(rows)

    @staticmethod
    def _cell(text: str) -> str:
        return " ".join(text.split()).replace("|", "\\|")

    def _row(self, entry: ErrorEntry) -> str:
        code = str(entry.code)
        name = entry.qualname.rsplit(".", 1)[-1]
        retired = " *(retired)*" if entry.retired else ""
        return (
            f'| <a id="{code.lower()}"></a>`{code}` | `{name}`: {self._cell(entry.title)}{retired} '
            f"| {self._cell(entry.cause)} | {self._cell(entry.fix)} |"
        )

    def apply(self, document: str, catalog: ErrorCatalogInterface) -> str:
        replacement = f"{self._begin}\n{self.block(catalog)}\n{self._end}"
        if not self._pattern.search(document):
            raise ValueError(f"the page has no {self._begin!r} ... {self._end!r} block")
        return self._pattern.sub(lambda _: replacement, document, count=1)

    def drift(self, document: str, catalog: ErrorCatalogInterface) -> bool:
        if not self._pattern.search(document):
            return True
        return self.apply(document, catalog) != document


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog=SCRIPT, description=__doc__.splitlines()[0])
    parser.add_argument("verb", choices=("render", "check"))
    parser.add_argument("--config", default=DEFAULT_CONFIG)
    args = parser.parse_args(argv)
    settings = tomllib.loads((REPO / args.config).read_text(encoding="utf-8"))["error_catalog"]
    catalog = ErrorCatalog.from_toml((REPO / settings["catalog"]).read_text(encoding="utf-8"))
    page = REPO / settings["docs_page"]
    document = page.read_text(encoding="utf-8")
    renderer = ErrorPage(settings["block"])
    if args.verb == "check":
        if renderer.drift(document, catalog):
            print(
                f"{settings['docs_page']} is out of step with the error catalog; run: {SCRIPT} render"
            )
            return 1
        print(f"{settings['docs_page']} matches the error catalog")
        return 0
    page.write_text(renderer.apply(document, catalog), encoding="utf-8")
    print(f"rewrote {settings['docs_page']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
