SCRIPT = "first_hour.py"
DEFAULT_CONFIG = "scripts/first_hour.toml"
SCHEMA = "vibey-first-hour/1"
SURVEY_SCHEMA = "vibey-first-hour-survey/1"
BEGIN = "<!-- BEGIN GENERATED first-hour — regenerated by scripts/first_hour.py -->"
END = "<!-- END GENERATED first-hour -->"
BLOCK = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.DOTALL)
REQUIRED = (
    "record",
    "survey_record",
    "guide",
    "owner",
    "repository_url",
    "branch",
    "runner",
    "substitutions",
    "step_timeout_s",
    "steps",
    "survey",
)
REQUIRED_SURVEY = ("months", "label", "title", "intro", "questions")
REQUIRED_STEP = ("name", "guide_step", "cwd", "argv")


@dataclass(frozen=True)
class StepOutcome:
    returncode: int
    seconds: float
    tail: str


class SubprocessRunner:
    """Runs one declared step; a missing tool or a timeout is an outcome, not a crash."""

    def run(
        self, argv: Sequence[str], *, cwd: Path, timeout: float, env: Mapping[str, str]
    ) -> StepOutcome:
        started = time.monotonic()
        try:
            done = subprocess.run(  # noqa: S603  # nosec B603 -- declared argv, no shell
                list(argv),
                cwd=cwd,
                env=dict(env),
                capture_output=True,
                text=True,
                timeout=timeout,
                check=False,
            )
        except FileNotFoundError as exc:
            return StepOutcome(127, time.monotonic() - started, str(exc))
        except subprocess.TimeoutExpired:
            return StepOutcome(124, time.monotonic() - started, f"timed out after {timeout:g} s")
        lines = (done.stderr or done.stdout).strip().splitlines()
        return StepOutcome(
            done.returncode, time.monotonic() - started, " / ".join(lines[-3:])[:300]
        )


class SystemClock:
    def now(self) -> str:
        return datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ")


class FirstHourSettings:
    """The declared configuration, with nothing defaulted: a missing key is an error."""

    def __init__(self, table: Mapping[str, Any]) -> None:
        for key in REQUIRED:
            if key not in table:
                raise ValueError(f"[first_hour] is missing {key!r}")
        for key in REQUIRED_SURVEY:
            if key not in table["survey"]:
                raise ValueError(f"[first_hour.survey] is missing {key!r}")
        for step in table["steps"]:
            for key in REQUIRED_STEP:
                if key not in step:
                    raise ValueError(
                        f"[[first_hour.steps]] {step.get('name', '?')!r} is missing {key!r}"
                    )
            if step["cwd"] not in ("workdir", "clone"):
                raise ValueError(f"step {step['name']!r}: cwd must be 'workdir' or 'clone'")
        if not table["steps"]:
            raise ValueError("[first_hour] declares no steps")
        self.table = table

    @classmethod
    def load(cls, path: Path) -> FirstHourSettings:
        with path.open("rb") as handle:
            return cls(tomllib.load(handle)["first_hour"])

    def __getitem__(self, key: str) -> Any:
        return self.table[key]


class FirstHourLedger(FirstHourLedgerInterface):
    """A JSON-lines record. Appending is the only write; an identity is recorded once."""

    def __init__(self, path: Path, key: str) -> None:
        self.path = path
        self.key = key

    def read(self) -> list[dict[str, Any]]:
        if not self.path.exists():
            return []
        records: list[dict[str, Any]] = []
        seen: set[str] = set()
        for number, line in enumerate(self.path.read_text(encoding="utf-8").splitlines(), start=1):
            if not line.strip():
                continue
            try:
                record = json.loads(line)
                identity = str(record[self.key])
            except (ValueError, KeyError, TypeError) as exc:
                raise ValueError(f"{self.path}:{number}: {exc}") from exc
            if identity in seen:
                raise ValueError(f"{self.path}:{number}: {self.key} {identity} appears twice")
            seen.add(identity)
            records.append(record)
        return records

    def append(self, record: Mapping[str, Any]) -> bool:
        if any(str(r[self.key]) == str(record[self.key]) for r in self.read()):
            return False
        self.path.parent.mkdir(parents=True, exist_ok=True)
        existing = self.path.read_text(encoding="utf-8") if self.path.exists() else ""
        with self.path.open("a", encoding="utf-8") as handle:
            if existing and not existing.endswith("\n"):
                handle.write("\n")
            handle.write(json.dumps(record, sort_keys=True, ensure_ascii=False) + "\n")
        return True


class FirstHourMeasurer(FirstHourMeasurerInterface):
    """Performs the declared steps in order, stopping at the first that fails."""

    def __init__(
        self, settings: FirstHourSettings, runner: SubprocessRunner, clock: SystemClock
    ) -> None:
        self._cfg = settings
        self._runner = runner
        self._clock = clock

    def measure(self, workdir: Path, run_id: str, environ: Mapping[str, str]) -> dict[str, Any]:
        clone = workdir / "vibey"
        values = {
            "url": self._cfg["repository_url"],
            "branch": self._cfg["branch"],
            "dir": str(clone),
        }
        started = self._clock.now()
        steps: list[dict[str, Any]] = []
        failed = ""
        for spec in self._cfg["steps"]:
            if failed:
                steps.append(self._skipped(spec, f"not run: step {failed!r} failed"))
                continue
            argv = [part.format(**values) for part in spec["argv"]]
            cwd = workdir if spec["cwd"] == "workdir" else clone
            outcome = self._runner.run(
                argv, cwd=cwd, timeout=float(self._cfg["step_timeout_s"]), env=environ
            )
            steps.append(
                {
                    "name": spec["name"],
                    "guide_step": spec["guide_step"],
                    "status": "passed" if outcome.returncode == 0 else "failed",
                    "seconds": round(outcome.seconds, 1),
                    **(
                        {}
                        if outcome.returncode == 0
                        else {"reason": f"exit {outcome.returncode}: {outcome.tail}"}
                    ),
                }
            )
            if outcome.returncode:
                failed = str(spec["name"])
        complete = not failed
        return {
            "schema": SCHEMA,
            "run_id": run_id,
            "measured_at": started,
            "commit": self._head(clone, environ),
            "runner": self._cfg["runner"],
            "substitutions": list(self._cfg["substitutions"]),
            "complete": complete,
            "total_seconds": round(sum(s["seconds"] for s in steps if s["status"] == "passed"), 1),
            "steps": steps,
        }

    @staticmethod
    def _skipped(spec: Mapping[str, Any], reason: str) -> dict[str, Any]:
        return {
            "name": spec["name"],
            "guide_step": spec["guide_step"],
            "status": "skipped",
            "seconds": 0.0,
            "reason": reason,
        }

    def _head(self, clone: Path, environ: Mapping[str, str]) -> str:
        if not clone.exists():
            return ""
        outcome = self._runner.run(["git", "rev-parse", "HEAD"], cwd=clone, timeout=60, env=environ)
        return outcome.tail if outcome.returncode == 0 else ""


class GuideRenderer(GuideRendererInterface):
    """The guide's GENERATED block: the latest complete run, what stood in, and the owner."""

    def __init__(self, settings: FirstHourSettings) -> None:
        self._cfg = settings

    @staticmethod
    def duration(seconds: float) -> str:
        whole = int(round(seconds))
        minutes, rest = divmod(whole, 60)
        return f"{minutes} min {rest} s" if minutes else f"{rest} s"

    def block(self, records: Sequence[Mapping[str, Any]]) -> str:
        owner = f"@{self._cfg['owner']}"
        complete = [r for r in records if r["complete"]]
        if not complete:
            body = (
                "**Not yet measured.** No complete run is recorded, so this guide states no "
                f"time of its own. The first-hour job is owned by {owner}."
            )
        else:
            latest = max(complete, key=lambda r: r["measured_at"])
            rows = "\n".join(
                f"| {s['guide_step']} | {s['name']} | {self.duration(s['seconds'])} |"
                for s in latest["steps"]
            )
            subs = "\n".join(f"- {text}" for text in latest["substitutions"])
            body = (
                f"**Measured: {self.duration(latest['total_seconds'])}** for steps 1 to 3, from an empty "
                f"directory, on {latest['runner']}, at commit `{latest['commit'][:8]}` on "
                f"{latest['measured_at'][:10]} ([the record](docs/architecture/evidence/first-hour.jsonl)). "
                "A person on their own machine will differ; what the figure leaves out:\n\n"
                f"{subs}\n\n| Step | What | Time |\n|---|---|---|\n{rows}\n\n"
                f"Owner: {owner}. Slower than this for you? That is a report about this guide: "
                "say so in the quarterly first-hour survey issue."
            )
        return f"{BEGIN}\n{body}\n{END}"

    def render(self, text: str, records: Sequence[Mapping[str, Any]]) -> str:
        if not BLOCK.search(text):
            raise ValueError(f"the guide has no {BEGIN!r} block to regenerate")
        return BLOCK.sub(lambda _: self.block(records), text, count=1)

    def problems(self, text: str, records: Sequence[Mapping[str, Any]]) -> list[str]:
        if not BLOCK.search(text):
            return [f"the guide has no {BEGIN!r} block"]
        if self.render(text, records) != text:
            return [
                "the guide's first-hour block is out of step with the record; run `first_hour.py render`"
            ]
        return []


class SurveyCollector(SurveyCollectorInterface):
    """The survey: its text, and every answer folded in by comment id."""

    def __init__(self, settings: FirstHourSettings, ledger: FirstHourLedgerInterface) -> None:
        self._cfg = settings
        self._ledger = ledger

    @staticmethod
    def quarter(today: datetime) -> str:
        return f"{today.year}-Q{(today.month - 1) // 3 + 1}"

    def due(self, today: datetime) -> bool:
        return today.month in self._cfg["survey"]["months"]

    def title(self, quarter: str) -> str:
        return str(self._cfg["survey"]["title"]).format(quarter=quarter)

    def body(self, quarter: str) -> str:
        survey = self._cfg["survey"]
        questions = "\n".join(f"{n}. {q}" for n, q in enumerate(survey["questions"], start=1))
        return (
            f"{survey['intro']}\n\n{questions}\n\nOwner: @{self._cfg['owner']}. "
            f"Quarter: {quarter}.\n\n<!-- first-hour-survey {quarter} -->"
        )

    def collect(self, comments: Sequence[Mapping[str, Any]], quarter: str) -> int:
        added = 0
        for comment in sorted(comments, key=lambda c: int(c["id"])):
            if str(comment.get("user", {}).get("type", "")) == "Bot":
                continue
            record = {
                "schema": SURVEY_SCHEMA,
                "comment_id": int(comment["id"]),
                "quarter": quarter,
                "created_at": str(comment["created_at"]),
                "url": str(comment.get("html_url", "")),
                "answer": str(comment["body"]),
            }
            added += self._ledger.append(record)
        return added


class FirstHourCli:
    def __init__(self, root: Path, clock: SystemClock | None = None) -> None:
        self.root = root
        self.clock = clock or SystemClock()

    def _settings(self, args: argparse.Namespace) -> FirstHourSettings:
        return FirstHourSettings.load(self.root / args.config)

    def _ledger(self, settings: FirstHourSettings, name: str, key: str) -> FirstHourLedger:
        return FirstHourLedger(self.root / settings[name], key)

    @staticmethod
    def parser() -> argparse.ArgumentParser:
        parser = argparse.ArgumentParser(
            prog=SCRIPT, description=__doc__.splitlines()[0] if __doc__ else ""
        )
        parser.add_argument("--config", default=DEFAULT_CONFIG)
        sub = parser.add_subparsers(dest="command", required=True)
        measure = sub.add_parser("measure")
        measure.add_argument("--workdir", required=True, type=Path)
        measure.add_argument("--run-id", required=True)
        sub.add_parser("render")
        sub.add_parser("check")
        sub.add_parser("survey-body").add_argument("--today", default=None)
        sub.add_parser("survey-title").add_argument("--today", default=None)
        sub.add_parser("survey-due").add_argument("--today", default=None)
        collect = sub.add_parser("survey-collect")
        collect.add_argument("--comments", required=True, type=Path)
        collect.add_argument("--quarter", required=True)
        return parser

    def _today(self, args: argparse.Namespace) -> datetime:
        text = getattr(args, "today", None)
        return datetime.fromisoformat(text) if text else datetime.now(UTC)

    def run(self, argv: Sequence[str], environ: Mapping[str, str] | None = None) -> int:
        args = self.parser().parse_args(list(argv))
        try:
            settings = self._settings(args)
        except (OSError, ValueError, KeyError, tomllib.TOMLDecodeError) as exc:
            print(f"{SCRIPT}: {exc}", file=sys.stderr)
            return 2
        try:
            return self._dispatch(args, settings, environ or {})
        except (OSError, ValueError, KeyError, TypeError) as exc:
            print(f"{SCRIPT}: {exc}", file=sys.stderr)
            return 1

    def _dispatch(
        self, args: argparse.Namespace, settings: FirstHourSettings, environ: Mapping[str, str]
    ) -> int:
        ledger = self._ledger(settings, "record", "run_id")
        survey = SurveyCollector(settings, self._ledger(settings, "survey_record", "comment_id"))
        if args.command == "measure":
            args.workdir.mkdir(parents=True, exist_ok=True)
            if any(args.workdir.iterdir()):
                raise ValueError(f"{args.workdir} is not empty; the first hour starts from nothing")
            measurer = FirstHourMeasurer(settings, SubprocessRunner(), self.clock)
            record = measurer.measure(args.workdir, args.run_id, environ)
            added = ledger.append(record)
            state = "complete" if record["complete"] else "did not complete"
            print(
                f"{SCRIPT}: run {args.run_id} {state}: {GuideRenderer.duration(record['total_seconds'])}"
                f"{'' if added else ' (already recorded)'}"
            )
            # The record is kept whether or not the run completed: a failed first hour is
            # the most useful line in it. The exit status says which it was.
            return 0 if record["complete"] else 1
        guide_path = self.root / settings["guide"]
        renderer = GuideRenderer(settings)
        if args.command == "render":
            guide_path.write_text(
                renderer.render(guide_path.read_text(encoding="utf-8"), ledger.read()),
                encoding="utf-8",
            )
            return 0
        if args.command == "check":
            problems = renderer.problems(guide_path.read_text(encoding="utf-8"), ledger.read())
            self._ledger(settings, "survey_record", "comment_id").read()
            for problem in problems:
                print(f"{SCRIPT}: {problem}", file=sys.stderr)
            return 1 if problems else 0
        today = self._today(args)
        if args.command == "survey-due":
            return 0 if survey.due(today) else 1
        quarter = survey.quarter(today)
        if args.command == "survey-title":
            print(survey.title(quarter))
            return 0
        if args.command == "survey-body":
            print(survey.body(quarter))
            return 0
        comments = json.loads(args.comments.read_text(encoding="utf-8"))
        if not isinstance(comments, list):
            raise ValueError(f"{args.comments}: expected a JSON list of comments")
        print(f"{SCRIPT}: recorded {survey.collect(comments, args.quarter)} new answer(s)")
        return 0


