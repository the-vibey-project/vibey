"""How long the documented first hour takes, measured, and what people say about it (#1692).

    python scripts/first_hour.py measure --workdir DIR   # perform the guide in DIR, time each step
    python scripts/first_hour.py render                  # rewrite the guide's GENERATED block
    python scripts/first_hour.py check                   # exit 1 if the record or the guide is out of step
    python scripts/first_hour.py survey-body             # print this quarter's survey text
    python scripts/first_hour.py survey-due              # exit 0 when a survey opens this month
    python scripts/first_hour.py survey-collect --comments FILE --quarter 2026-Q4

The measurement performs CONTRIBUTING.md "Your first hour" in an empty directory, times every
step, and appends one line to an append-only record. A step that fails ends the run: the
record says which step, and a run that did not complete never becomes the time the guide
states (sub-doctrine 10.f: a figure over an unknown subset is not evidence). The guide states
the latest complete run, with what the runner stood in for. Survey answers are folded into a
second record by comment id, so every answer is read once and none is skipped for arriving
late or out of order (sub-doctrine 10.g); an unreadable source changes nothing and fails.
Everything configurable is in `scripts/first_hour.toml` (ADR-0051).
"""

