"""Binaries of every user interface, for every supported platform, on every GitHub Release.

    python scripts/release_binaries.py context                 # the release's tag, branch, workflow
    python scripts/release_binaries.py plan --mode M --target SHA [--github-output F]
    python scripts/release_binaries.py check                   # exit 1 when anything drifted
    python scripts/release_binaries.py render                  # rewrite the downloads table
    python scripts/release_binaries.py flatpak-manifest --manifest M --module X --source D --out F
    python scripts/release_binaries.py pypi-fetch --project P --version V --out D
    python scripts/release_binaries.py collect --dir D --expected JSON --optional JSON

`scripts/release_binaries.toml` declares every target: one user interface on one platform,
and whether it is built on every release, is built only while a credential is set (a
release without it says so and keeps one tracking issue open), or is not supported (with
the reason). `.github/workflows/release-binaries.yml` runs
after every successful `Release` on main; its `plan` job asks this script for the matrix,
so the workflow builds what the configuration declares and nothing it does not. `check`
holds the two together in the other direction too -- every declared builder has its job,
every job is a declared builder or one of the workflow's own -- and holds the downloads
page to the configuration (sub-doctrine 12.e: the check that says out loud when the step
was missed). CI runs it from tests/meta/test_release_binaries.py.

Nothing here reimplements what the family already does (sub-doctrine 10.e): the release's
tag, its branch and the name of the workflow it follows are read through vibey-gh's own
configuration loader and version reader, exactly as `vibey-gh github-release` computes the
tag it creates; the Linux architectures and their runners are read from the requirements
matrix (`scripts/minimum_specs.toml`), the one place the supported set is declared.
"""

