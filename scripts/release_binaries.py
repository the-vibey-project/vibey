class WorkflowChecker(WorkflowCheckerInterface):
    """Implements `WorkflowCheckerInterface`: the workflow builds exactly what is declared."""

    def __init__(
        self,
        catalogue: TargetCatalogueInterface,
        settings: Settings,
        context: ReleaseContext,
    ) -> None:
        self._catalogue = catalogue
        self._settings = settings
        self._context = context

    def problems(self, workflow: Mapping[Any, Any]) -> list[str]:
        found: list[str] = []
        jobs: Mapping[str, Any] = workflow.get("jobs") or {}
        builders = list(self._catalogue.builders())
        infrastructure = list(self._settings.infrastructure_jobs)
        found += self._trigger(workflow)
        for job in infrastructure:
            if job not in jobs:
                found.append(f"the workflow has no `{job}` job")
        unsupported = {
            t.builder for t in self._catalogue.targets() if t.status == "unsupported"
        } - set(builders)
        for job in jobs:
            if job not in builders and job not in infrastructure and job not in unsupported:
                found.append(
                    f"job `{job}` builds nothing scripts/release_binaries.toml declares "
                    "(declare its targets, or remove the job)"
                )
        plan_outputs = (jobs.get("plan") or {}).get("outputs") or {}
        for builder in builders:
            spec = jobs.get(builder)
            if spec is None:
                found.append(f"builder `{builder}` is declared but the workflow has no job for it")
                continue
            found += self._builder(builder, spec, plan_outputs)
        for builder in sorted(unsupported & set(jobs)):
            found.append(f"job `{builder}` builds a target declared unsupported")
        collect = jobs.get("collect") or {}
        waits = set(self._needs(collect))
        missing = [builder for builder in builders if builder not in waits]
        if collect and missing:
            found.append(f"`collect` does not wait for: {', '.join(missing)}")
        return found

    def _trigger(self, workflow: Mapping[Any, Any]) -> list[str]:
        on = workflow.get("on", workflow.get(True)) or {}
        expected = {
            "workflows": [self._context.release_workflow],
            "types": ["completed"],
            "branches": [self._context.release_branch],
        }
        if not isinstance(on, dict) or on.get("workflow_run") != expected:
            return [
                f"the workflow must follow a completed `{self._context.release_workflow}` run on "
                f"`{self._context.release_branch}` (on.workflow_run == {expected})"
            ]
        return []

    @staticmethod
    def _needs(job: Mapping[str, Any]) -> list[str]:
        needs = job.get("needs") or []
        return [needs] if isinstance(needs, str) else list(needs)

    def _builder(
        self, builder: str, job: Mapping[str, Any], plan_outputs: Mapping[str, Any]
    ) -> list[str]:
        found: list[str] = []
        output = f"${{{{ steps.plan.outputs.{builder} }}}}"
        if plan_outputs.get(builder) != output:
            found.append(f"the `plan` job must declare output `{builder}: {output}`")
        if "plan" not in self._needs(job):
            found.append(f"job `{builder}` must need `plan`")
        matrix = (job.get("strategy") or {}).get("matrix")
        expected = f"${{{{ fromJSON(needs.plan.outputs.{builder}) }}}}"
        if matrix != expected:
            found.append(f"job `{builder}`'s matrix must be `{expected}`, not {matrix!r}")
        if job.get("runs-on") != "${{ matrix.runner }}":
            found.append(f"job `{builder}` must run on `${{{{ matrix.runner }}}}`")
        text = json.dumps(job)
        for target in self._catalogue.targets():
            if target.builder != builder:
                continue
            if target.status == "credential":
                found += self._tracked(builder, text, target.credentials, "matrix.tracking_key")
            if target.signing_credentials:
                found += self._tracked(
                    builder, text, target.signing_credentials, "matrix.signing_tracking_key"
                )
        return sorted(set(found), key=found.index)

    @staticmethod
    def _tracked(builder: str, text: str, secrets: Sequence[str], key: str) -> list[str]:
        """A credential the repository may lack: read, said out loud, tracked by one issue."""
        found: list[str] = []
        for secret in secrets:
            if f"secrets.{secret}" not in text:
                found.append(f"job `{builder}` never reads the credential `{secret}`")
        for verb in ("raise", "resolve"):
            if f"vibey-gh tracking-issue {verb}" not in text:
                found.append(
                    f"job `{builder}` waits for a credential but never runs "
                    f"`vibey-gh tracking-issue {verb}`"
                )
        if key not in text:
            found.append(
                f"job `{builder}` must key its tracking issue on the target's key (`{key}`)"
            )
        return found


