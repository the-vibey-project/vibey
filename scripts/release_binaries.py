class ReleaseBinariesError(RuntimeError):
    """A declaration, a workflow or a fetched file that is not what it must be."""


# ------------------------------------------------------------------------ settings


@dataclass(frozen=True)
class Settings:
    """`[release_binaries]` from the TOML, with every path resolved against the repository."""

    root: Path
    workflow: Path
    downloads_page: Path
    gh_config: Path
    linux_arches_source: Path
    linux_arches_table: str
    checksums_asset: str
    infrastructure_jobs: tuple[str, ...]
    release_wait_s: int
    poll_s: int
    pypi_wait_s: int
    pypi_json_url: str
    uis: Mapping[str, Mapping[str, Any]]
    targets: tuple[Mapping[str, Any], ...]

    @classmethod
    def load(cls, path: Path = DEFAULT_CONFIG, root: Path = REPO) -> Settings:
        data = tomllib.loads(path.read_text(encoding="utf-8"))
        section = data.get("release_binaries")
        if not isinstance(section, dict):
            raise ReleaseBinariesError(f"{path} declares no [release_binaries] table")
        try:
            return cls(
                root=root,
                workflow=root / section["workflow"],
                downloads_page=root / section["downloads_page"],
                gh_config=root / section["gh_config"],
                linux_arches_source=root / section["linux_arches_source"],
                linux_arches_table=str(section["linux_arches_table"]),
                checksums_asset=str(section["checksums_asset"]),
                infrastructure_jobs=tuple(section["infrastructure_jobs"]),
                release_wait_s=int(section["release_wait_s"]),
                poll_s=int(section["poll_s"]),
                pypi_wait_s=int(section["pypi_wait_s"]),
                pypi_json_url=str(section["pypi_json_url"]),
                uis=dict(section["uis"]),
                targets=tuple(section["targets"]),
            )
        except KeyError as missing:
            raise ReleaseBinariesError(f"{path}: [release_binaries] lacks {missing}") from None


# ------------------------------------------------------------------------- targets


@dataclass(frozen=True)
class Target:
    """One user interface on one platform (and one architecture, where that matters)."""

    id: str
    ui: str
    ui_name: str
    builder: str
    status: str
    platform: str
    arch: str
    runner: str
    version: str
    assets: tuple[str, ...]
    #: The asset names with the version left as a placeholder: what the downloads page shows.
    asset_patterns: tuple[str, ...]
    signing: str
    install: str = ""
    note: str = ""
    reason: str = ""
    needs: str = ""
    credentials: tuple[str, ...] = ()
    tracking_key: str = ""
    #: A built target whose signing a credential would raise: what it reads, and the issue
    #: the release keeps open while any of it is missing.
    signing_credentials: tuple[str, ...] = ()
    signing_tracking_key: str = ""
    signing_needs: str = ""
    with_: Mapping[str, Any] = field(default_factory=dict)

    def row(self) -> dict[str, Any]:
        """The builder's matrix row: what its job reads as `matrix.*`."""
        row: dict[str, Any] = {
            "id": self.id,
            "runner": self.runner,
            "arch": self.arch,
            "version": self.version,
            "assets": " ".join(self.assets),
            "artifact": f"release-binary-{self.id}",
        }
        if self.status == "credential":
            row["tracking_key"] = self.tracking_key
            row["credentials"] = " ".join(self.credentials)
            row["needs"] = self.needs
        if self.signing_credentials:
            row["signing_tracking_key"] = self.signing_tracking_key
            row["signing_credentials"] = " ".join(self.signing_credentials)
            row["signing_needs"] = self.signing_needs
        row.update(self.with_)
        return row


class VersionReader:
    """Reads one interface's version: the first group of a pattern in a declared file."""

    def __init__(self, root: Path) -> None:
        self._root = root

    def read(self, ui: str, declaration: Mapping[str, Any]) -> str:
        path = self._root / str(declaration["version_file"])
        match = re.search(str(declaration["version_pattern"]), path.read_text(encoding="utf-8"))
        if match is None:
            raise ReleaseBinariesError(
                f"[release_binaries.uis.{ui}]: no version matches its pattern in {path}"
            )
        return match.group(1)


class LinuxArches:
    """The supported Linux architectures and the native runner of each, read from the
    requirements matrix: the one place the supported set is declared."""

    def __init__(self, source: Path, table: str) -> None:
        self._source = source
        self._table = table

    def runners(self) -> dict[str, str]:
        node: Any = tomllib.loads(self._source.read_text(encoding="utf-8"))
        for key in self._table.split("."):
            if not isinstance(node, dict) or key not in node:
                raise ReleaseBinariesError(f"{self._source} has no [{self._table}] table")
            node = node[key]
        if not isinstance(node, dict) or not node:
            raise ReleaseBinariesError(f"[{self._table}] in {self._source} declares no arch")
        return {str(arch): str(spec["runner"]) for arch, spec in node.items()}


class TargetCatalogue(TargetCatalogueInterface):
    """Implements `TargetCatalogueInterface` over `[release_binaries]`."""

    def __init__(
        self,
        settings: Settings,
        versions: VersionReader | None = None,
        arches: LinuxArches | None = None,
    ) -> None:
        self._settings = settings
        self._versions = versions or VersionReader(settings.root)
        self._arches = arches or LinuxArches(
            settings.linux_arches_source, settings.linux_arches_table
        )
        self._targets: list[Target] | None = None

    def targets(self) -> list[Target]:
        if self._targets is None:
            self._targets = self._expand()
        return list(self._targets)

    def builders(self) -> list[str]:
        seen: list[str] = []
        for target in self.targets():
            if target.status != "unsupported" and target.builder not in seen:
                seen.append(target.builder)
        return seen

    def _expand(self) -> list[Target]:
        found: list[Target] = []
        versions: dict[str, str] = {}
        for index, spec in enumerate(self._settings.targets):
            where = f"[[release_binaries.targets]] #{index + 1}"
            ui = str(spec.get("ui", ""))
            if ui not in self._settings.uis:
                raise ReleaseBinariesError(f"{where}: ui {ui!r} is not a [release_binaries.uis]")
            status = str(spec.get("status", ""))
            if status not in STATUSES:
                raise ReleaseBinariesError(f"{where}: status must be one of {STATUSES}")
            signing = str(spec.get("signing", ""))
            if signing not in SIGNING:
                raise ReleaseBinariesError(f"{where}: signing must be one of {tuple(SIGNING)}")
            self._require(where, spec, status)
            if ui not in versions:
                versions[ui] = self._versions.read(ui, self._settings.uis[ui])
            if spec.get("per_linux_arch", False):
                cells = list(self._arches.runners().items())
            else:
                cells = [(str(spec.get("arch", "any")), str(spec.get("runner", "")))]
            for arch, runner in cells:
                found.append(self._target(spec, ui, status, signing, arch, runner, versions[ui]))
        ids = [target.id for target in found]
        duplicates = sorted({one for one in ids if ids.count(one) > 1})
        if duplicates:
            raise ReleaseBinariesError(f"target ids declared twice: {', '.join(duplicates)}")
        assets = [asset for target in found for asset in target.assets]
        clashes = sorted({one for one in assets if assets.count(one) > 1})
        if clashes:
            raise ReleaseBinariesError(f"asset names produced twice: {', '.join(clashes)}")
        return found

    @staticmethod
    def _require(where: str, spec: Mapping[str, Any], status: str) -> None:
        needed = {
            "build": ("id", "builder", "platform", "assets"),
            "credential": ("id", "builder", "platform", "assets", "credentials", "tracking_key"),
            "unsupported": ("id", "builder", "platform", "reason"),
        }[status]
        missing = [key for key in needed if not spec.get(key)]
        if status == "credential" and not spec.get("needs"):
            missing.append("needs")
        if status != "unsupported" and not spec.get("per_linux_arch") and not spec.get("runner"):
            missing.append("runner (or per_linux_arch)")
        if spec.get("signing_credentials"):
            if status != "build":
                missing.append("status = build (only a built target has signing to raise)")
            missing += [
                key for key in ("signing_tracking_key", "signing_needs") if not spec.get(key)
            ]
        if missing:
            raise ReleaseBinariesError(f"{where} ({status}) lacks {', '.join(missing)}")

    def _target(
        self,
        spec: Mapping[str, Any],
        ui: str,
        status: str,
        signing: str,
        arch: str,
        runner: str,
        version: str,
    ) -> Target:
        def fill(text: str, shown: str) -> str:
            return text.replace("{arch}", arch).replace("{version}", shown)

        patterns = tuple(str(asset) for asset in spec.get("assets", []))
        return Target(
            id=fill(str(spec["id"]), version),
            ui=ui,
            ui_name=str(self._settings.uis[ui]["name"]),
            builder=str(spec["builder"]),
            status=status,
            platform=str(spec["platform"]),
            arch=arch,
            runner=runner,
            version=version,
            assets=tuple(fill(asset, version) for asset in patterns),
            asset_patterns=tuple(fill(asset, VERSION_PLACEHOLDER) for asset in patterns),
            signing=signing,
            install=fill(str(spec.get("install", "")), VERSION_PLACEHOLDER),
            note=str(spec.get("note", "")),
            reason=str(spec.get("reason", "")),
            needs=str(spec.get("needs", "")),
            credentials=tuple(str(one) for one in spec.get("credentials", [])),
            tracking_key=str(spec.get("tracking_key", "")),
            signing_credentials=tuple(str(one) for one in spec.get("signing_credentials", [])),
            signing_tracking_key=str(spec.get("signing_tracking_key", "")),
            signing_needs=str(spec.get("signing_needs", "")),
            with_=dict(spec.get("with", {})),
        )


