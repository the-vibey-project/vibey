class DownloadsRenderer(DownloadsRendererInterface):
    """Implements `DownloadsRendererInterface`: the catalogue as the downloads page's table."""

    def __init__(self, catalogue: TargetCatalogueInterface, settings: Settings) -> None:
        self._catalogue = catalogue
        self._settings = settings

    @staticmethod
    def _credentials(target: Target) -> str:
        """`A` is / `A` and `B` are: the credentials a target is built under, named."""
        names = [f"`{name}`" for name in target.credentials]
        joined = names[0] if len(names) == 1 else ", ".join(names[:-1]) + " and " + names[-1]
        return f"{joined} {'is' if len(names) == 1 else 'are'} set"

    def render(self) -> str:
        targets: list[Target] = list(self._catalogue.targets())
        built = [t for t in targets if t.status == "build"]
        # A target waiting for a credential is built by any release run while the credential
        # is set, so it is listed with the rest; the page cannot know whether the secret is set
        # today, so it says on what the file depends, never that it is or is not built.
        waiting = [t for t in targets if t.status == "credential"]
        listed = [t for t in targets if t.status in ("build", "credential")]
        lines = [
            f"*Generated from [`scripts/release_binaries.toml`]"
            f"(https://github.com/the-vibey-project/vibey/blob/develop/scripts/release_binaries.toml) "
            f"by `{SCRIPT} render`; do not edit inside these markers. `{VERSION_PLACEHOLDER}` "
            "is each interface's own version.*",
            "",
            "| Interface | Platform | Architecture | File | Signing |",
            "|---|---|---|---|---|",
        ]
        for t in listed:
            files = "<br>".join(f"`{asset}`" for asset in t.asset_patterns)
            signing = SIGNING[t.signing]
            if t.status == "credential":
                signing += f" (built only while {self._credentials(t)})"
            lines.append(f"| {t.ui_name} | {t.platform} | {t.arch} | {files} | {signing} |")
        lines += [
            "",
            f"Every file is listed in `{self._settings.checksums_asset}` beside it, with its "
            "SHA-256, and carries a GitHub build-provenance attestation.",
            "",
            "### Installing each",
            "",
        ]
        for t in listed:
            if t.status == "credential" and not t.note:
                continue
            title = f"**{t.ui_name}, {t.platform}" + (f", {t.arch}**" if t.arch != "any" else "**")
            lines.append(f"- {title}: {t.note}" + (f" `{t.install}`" if t.install else ""))
        raised: dict[str, Target] = {}
        for t in built:
            if t.signing_credentials:
                raised.setdefault(t.signing_tracking_key, t)
        if raised:
            lines += ["", "### Signing that waits for a credential", ""]
            for t in raised.values():
                lines.append(
                    f"- **{t.ui_name}, {t.platform}**: built and attached on every release, "
                    f"{SIGNING[t.signing][0].lower()}{SIGNING[t.signing][1:]}. {t.signing_needs} "
                    f"The release workflow keeps one tracking issue open until they are set "
                    f"(`{t.signing_tracking_key}`)."
                )
        if waiting:
            lines += ["", "### Built only while a credential is set", ""]
            for t in waiting:
                lines.append(
                    f"- **{t.ui_name}, {t.platform}**: built and attached by a release only "
                    f"while {self._credentials(t)}. {t.needs} Without it nothing is built for "
                    f"this target, the release says so and keeps one tracking issue open "
                    f"(`{t.tracking_key}`), and the release itself is unaffected."
                )
        unsupported = [t for t in targets if t.status == "unsupported"]
        if unsupported:
            lines += ["", "### Not supported", ""]
            for t in unsupported:
                lines.append(f"- **{t.ui_name}, {t.platform}**: {t.reason}")
        return "\n".join(lines)

    def apply(self, text: str) -> str:
        """`text` with its GENERATED block replaced by a fresh render."""
        if text.count(BEGIN) != 1 or text.count(END) != 1:
            raise ReleaseBinariesError(
                f"{self._settings.downloads_page} must carry exactly one GENERATED "
                "release:downloads block"
            )
        head, rest = text.split(BEGIN, 1)
        _, tail = rest.split(END, 1)
        return f"{head}{BEGIN}\n{self.render()}\n{END}{tail}"


# -------------------------------------------------------------------------- PyPI


class UrllibFetcher(HttpFetcherInterface):
    """Implements `HttpFetcherInterface` with the standard library."""

    def __init__(self, timeout_s: float = 120.0) -> None:
        self._timeout = timeout_s

    def get(self, url: str) -> bytes:
        if not url.startswith("https://"):
            raise ReleaseBinariesError(f"refusing a non-HTTPS URL: {url}")
        with urllib.request.urlopen(url, timeout=self._timeout) as response:  # noqa: S310
            body: bytes = response.read()
            return body


class PypiFetcher(PypiFetcherInterface):
    """Implements `PypiFetcherInterface` over PyPI's JSON API, waiting for a late upload."""

    def __init__(
        self,
        http: HttpFetcherInterface,
        url_template: str,
        *,
        wait_s: int,
        poll_s: int,
        sleep: Callable[[float], None] = time.sleep,
    ) -> None:
        self._http = http
        self._template = url_template
        self._wait_s = wait_s
        self._poll_s = poll_s
        self._sleep = sleep

    def fetch(self, project: str, version: str, out: Path) -> list[Path]:
        files = self._listing(project, version)
        out.mkdir(parents=True, exist_ok=True)
        written: list[Path] = []
        for entry in files:
            name = str(entry["filename"])
            if "/" in name or name.startswith("."):
                raise ReleaseBinariesError(f"PyPI listed an unsafe file name: {name!r}")
            body = self._http.get(str(entry["url"]))
            digest = hashlib.sha256(body).hexdigest()
            if digest != entry["digests"]["sha256"]:
                raise ReleaseBinariesError(
                    f"{name}: SHA-256 {digest} is not the {entry['digests']['sha256']} PyPI records"
                )
            path = out / name
            path.write_bytes(body)
            written.append(path)
        return written

    def _listing(self, project: str, version: str) -> list[Mapping[str, Any]]:
        url = self._template.format(project=project, version=version)
        waited = 0
        while True:
            try:
                data = json.loads(self._http.get(url))
                files = list(data.get("urls") or [])
                if files:
                    return files
                reason = "no files are listed yet"
            except Exception as error:  # noqa: BLE001 -- every failure is retried, then reported
                reason = str(error)
            if waited >= self._wait_s:
                raise ReleaseBinariesError(
                    f"{project} {version} is not on PyPI after {waited}s: {reason}"
                )
            print(f"{project} {version}: {reason}; waiting {self._poll_s}s", file=sys.stderr)
            self._sleep(self._poll_s)
            waited += self._poll_s


# ------------------------------------------------------------------------ collect


class AssetCollector:
    """Holds the gathered files to the plan, then writes their checksum file."""

    def __init__(self, directory: Path, checksums_asset: str) -> None:
        self._directory = directory
        self._checksums = checksums_asset

    def collect(self, expected: Sequence[str], optional: Sequence[str]) -> list[str]:
        present = sorted(
            path.name
            for path in self._directory.iterdir()
            if path.is_file() and path.name != self._checksums
        )
        missing = [name for name in expected if name not in present]
        unexpected = [name for name in present if name not in expected and name not in optional]
        problems = []
        if missing:
            problems.append(f"missing: {', '.join(missing)}")
        if unexpected:
            problems.append(f"not declared: {', '.join(unexpected)}")
        if problems:
            raise ReleaseBinariesError("; ".join(problems))
        lines = []
        for name in present:
            digest = hashlib.sha256((self._directory / name).read_bytes()).hexdigest()
            lines.append(f"{digest}  {name}")
        (self._directory / self._checksums).write_text("\n".join(lines) + "\n", encoding="utf-8")
        return present


# ------------------------------------------------------------------------ flatpak


class FlatpakManifestLocalizer:
    """The declared Flatpak manifest with one module built from a local checkout.

    The declared manifest fetches the source from git, as Flathub requires. A release
    builds the commit it is releasing, already checked out, so the module's sources are
    replaced by that directory; nothing else in the manifest changes.
    """

    def localize(self, manifest: Path, module: str, source: Path) -> dict[str, Any]:
        import yaml  # type: ignore[import-untyped]  # PyYAML: only this command needs it.

        data = yaml.safe_load(manifest.read_text(encoding="utf-8"))
        modules = data.get("modules") or []
        hits = [m for m in modules if isinstance(m, dict) and m.get("name") == module]
        if len(hits) != 1:
            raise ReleaseBinariesError(f"{manifest} has no single module named {module!r}")
        hits[0]["sources"] = [{"type": "dir", "path": str(source.resolve())}]
        result: dict[str, Any] = data
        return result


# ---------------------------------------------------------------------------- CLI


class Cli:
    """The command line: each subcommand is one of the classes above, wired to real I/O."""

    def __init__(self, config: Path = DEFAULT_CONFIG, root: Path = REPO) -> None:
        self._config = config
        self._root = root

    def run(self, argv: Sequence[str] | None = None) -> int:
        args = self._parser().parse_args(argv)
        try:
            result: int = args.func(args)
            return result
        except ReleaseBinariesError as error:
            print(f"error: {error}", file=sys.stderr)
            return 1

    def _parser(self) -> argparse.ArgumentParser:
        parser = argparse.ArgumentParser(prog=SCRIPT, description=__doc__.split("\n")[0])
        sub = parser.add_subparsers(required=True)
        sub.add_parser("context", help="print the release's tag, branch and workflow").set_defaults(
            func=self._context
        )
        plan = sub.add_parser("plan", help="print the workflow's matrix for one run")
        plan.add_argument("--mode", required=True, choices=MODES)
        plan.add_argument("--target", required=True)
        plan.add_argument("--github-output", type=Path)
        plan.set_defaults(func=self._plan)
        sub.add_parser("check", help="exit 1 when the workflow or the page drifted").set_defaults(
            func=self._check
        )
        sub.add_parser("render", help="rewrite the downloads page's table").set_defaults(
            func=self._render
        )
        flatpak = sub.add_parser("flatpak-manifest", help="the manifest, built from a checkout")
        flatpak.add_argument("--manifest", required=True, type=Path)
        flatpak.add_argument("--module", required=True)
        flatpak.add_argument("--source", required=True, type=Path)
        flatpak.add_argument("--out", required=True, type=Path)
        flatpak.set_defaults(func=self._flatpak)
        pypi = sub.add_parser("pypi-fetch", help="fetch one version's files from PyPI")
        pypi.add_argument("--project", required=True)
        pypi.add_argument("--version", required=True)
        pypi.add_argument("--out", required=True, type=Path)
        pypi.set_defaults(func=self._pypi)
        collect = sub.add_parser("collect", help="hold the files to the plan; write checksums")
        collect.add_argument("--dir", required=True, type=Path)
        collect.add_argument("--expected", required=True)
        collect.add_argument("--optional", default="[]")
        collect.set_defaults(func=self._collect)
        return parser

    def _settings(self) -> Settings:
        return Settings.load(self._config, self._root)

    def _context(self, _args: argparse.Namespace) -> int:
        context = ReleaseContext.read(self._settings())
        print(f"tag={context.tag}")
        print(f"release_branch={context.release_branch}")
        print(f"release_workflow={context.release_workflow}")
        return 0

    def _plan(self, args: argparse.Namespace) -> int:
        settings = self._settings()
        planner = MatrixPlanner(TargetCatalogue(settings), settings)
        plan = planner.plan(
            mode=args.mode, target=args.target, tag=ReleaseContext.read(settings).tag
        )
        if args.github_output:
            with args.github_output.open("a", encoding="utf-8") as handle:
                handle.write(MatrixPlanner.github_output(plan))
        print(json.dumps(plan, indent=2))
        return 0

    def _check(self, _args: argparse.Namespace) -> int:
        import yaml  # a dev dependency; CI's gates run this (typed once, above)

        settings = self._settings()
        catalogue = TargetCatalogue(settings)
        workflow = yaml.safe_load(settings.workflow.read_text(encoding="utf-8"))
        problems = WorkflowChecker(catalogue, settings, ReleaseContext.read(settings)).problems(
            workflow
        )
        page = settings.downloads_page.read_text(encoding="utf-8")
        renderer = DownloadsRenderer(catalogue, settings)
        if renderer.apply(page) != page:
            problems.append(
                f"{settings.downloads_page.relative_to(settings.root)} is out of date: "
                f"run `python {SCRIPT} render`"
            )
        for problem in problems:
            print(f"drift: {problem}", file=sys.stderr)
        return 1 if problems else 0

    def _render(self, _args: argparse.Namespace) -> int:
        settings = self._settings()
        page = settings.downloads_page
        renderer = DownloadsRenderer(TargetCatalogue(settings), settings)
        page.write_text(renderer.apply(page.read_text(encoding="utf-8")), encoding="utf-8")
        print(f"rendered {page.relative_to(settings.root)}")
        return 0

    def _flatpak(self, args: argparse.Namespace) -> int:
        data = FlatpakManifestLocalizer().localize(args.manifest, args.module, args.source)
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
        print(f"wrote {args.out}")
        return 0

    def _pypi(self, args: argparse.Namespace) -> int:
        settings = self._settings()
        fetcher = PypiFetcher(
            UrllibFetcher(),
            settings.pypi_json_url,
            wait_s=settings.pypi_wait_s,
            poll_s=settings.poll_s,
        )
        for path in fetcher.fetch(args.project, args.version, args.out):
            print(f"fetched {path.name} (SHA-256 matches PyPI)")
        return 0

    def _collect(self, args: argparse.Namespace) -> int:
        settings = self._settings()
        collector = AssetCollector(args.dir, settings.checksums_asset)
        names = collector.collect(json.loads(args.expected), json.loads(args.optional))
        for name in names:
            print(f"collected {name}")
        print(f"wrote {settings.checksums_asset} over {len(names)} files")
        return 0


if __name__ == "__main__":
    sys.exit(Cli().run())
