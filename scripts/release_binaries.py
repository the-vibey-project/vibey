@dataclass(frozen=True)
class ReleaseContext:
    """The tag the release's GitHub Release carries, its branch, and the workflow it follows."""

    tag: str
    release_branch: str
    release_workflow: str

    @classmethod
    def read(cls, settings: Settings) -> ReleaseContext:
        # Imported here, not at the top: every other command runs on a bare interpreter in
        # the workflow (collect, pypi-fetch, flatpak-manifest), and only this one needs the
        # tree's own vibey-gh installed -- the plan job installs it, as openvsx.yml does.
        from vibey_gh.config import load_config
        from vibey_gh.versioning import read_version

        cfg = load_config(settings.root, settings.gh_config)
        return cls(
            tag=f"{cfg.github_release.tag_prefix}{read_version(cfg)}",
            release_branch=cfg.release_branch,
            release_workflow=cfg.workflow_names.release,
        )


class MatrixPlanner(MatrixPlannerInterface):
    """Implements `MatrixPlannerInterface`: one matrix per builder, from the catalogue."""

    def __init__(self, catalogue: TargetCatalogueInterface, settings: Settings) -> None:
        self._catalogue = catalogue
        self._settings = settings

    def plan(self, *, mode: str, target: str, tag: str) -> dict[str, Any]:
        if mode not in MODES:
            raise ReleaseBinariesError(f"mode must be one of {MODES}, not {mode!r}")
        targets: list[Target] = list(self._catalogue.targets())
        builders: dict[str, dict[str, list[dict[str, Any]]]] = {}
        for builder in self._catalogue.builders():
            rows = [t.row() for t in targets if t.builder == builder and t.status != "unsupported"]
            builders[builder] = {"include": rows}
        return {
            "mode": mode,
            "target": target,
            "tag": tag,
            "expected": [a for t in targets if t.status == "build" for a in t.assets],
            "optional": [a for t in targets if t.status == "credential" for a in t.assets],
            "checksums": self._settings.checksums_asset,
            "release_wait_s": self._settings.release_wait_s,
            "poll_s": self._settings.poll_s,
            "builders": builders,
        }

    @staticmethod
    def github_output(plan: Mapping[str, Any]) -> str:
        """The plan as `key=value` lines for `$GITHUB_OUTPUT`: one per builder, as JSON."""
        lines = [
            f"mode={plan['mode']}",
            f"target={plan['target']}",
            f"tag={plan['tag']}",
            f"expected={json.dumps(plan['expected'], separators=(',', ':'))}",
            f"optional={json.dumps(plan['optional'], separators=(',', ':'))}",
            f"checksums={plan['checksums']}",
            f"release_wait_s={plan['release_wait_s']}",
            f"poll_s={plan['poll_s']}",
        ]
        for builder, matrix in plan["builders"].items():
            lines.append(f"{builder}={json.dumps(matrix, separators=(',', ':'))}")
        return "\n".join(lines) + "\n"


