def page(body: str) -> str:
    return f"# A prompt\n\n{STATE}\n## The prompt\n\n```text\n{body}\n```\n"


class FakeRunner:
    """Answers `vibey-gh <sub> --help` for a fixed set of commands; echoes anything else."""

    def __init__(self, commands: set[str] | None = None, output: str = "evidence") -> None:
        self.commands = commands if commands is not None else {"version"}
        self.output = output
        self.calls: list[str] = []

    def run(self, command: str, timeout_s: float) -> tuple[int, str]:
        self.calls.append(command)
        if "-m vibey_gh" in command:
            sub = command.split("-m vibey_gh ", 1)[1].split()[0]
            return (0, "") if sub in self.commands else (2, "unknown")
        return 0, self.output


