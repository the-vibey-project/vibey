"""Whether the pre-commit framework's own hooks are installed in this clone (#1689).

`vibey-gh install` points `core.hooksPath` at `.githooks`, whose shims hand every stage to the
framework's generated hook. If that hook was never installed, the shim prints a warning and lets
the commit through (CONTRIBUTING.md), and a clone with no `core.hooksPath` has no shim at all:
the first anyone hears of it is the Provenance check failing after the push. `installed(local=True)`
now says so, beforehand (sub-doctrine 12.e).

The hook is looked for where `pre-commit install` writes it, `<git-common-dir>/hooks/<stage>`, asked
of git and never spelled `.git/hooks`: in a linked worktree `.git` is a file, and the common
directory is shared by every worktree (see `.githooks/framework-hook.sh`). `git rev-parse
--git-path hooks` is no answer either, since it honours `core.hooksPath`.

Only a repository that declares the framework (`.pre-commit-config.yaml`) is held to it.
"""

from __future__ import annotations

import subprocess
from pathlib import Path

from vibey_gh.config import GhConfig
from vibey_gh.interfaces.hook_inspector_interface import HookInspectorInterface

__all__ = ["CONFIG", "MARKER", "STAGES", "HookInspector"]

STAGES = ("pre-commit", "commit-msg", "pre-push")
"""The three stages `pre-commit install --hook-type` must be given; without them the commit-msg
and pre-push gates never run locally."""

CONFIG = ".pre-commit-config.yaml"

MARKER = "generated by pre-commit"
"""Text in the first lines of every hook the framework writes."""

_MARKER_WINDOW = 4096


class HookInspector(HookInspectorInterface):
    """Implements `HookInspectorInterface`."""

    def common_dir(self, cfg: GhConfig) -> Path | None:
        try:
            done = subprocess.run(
                ["git", "rev-parse", "--git-common-dir"],
                cwd=cfg.root,
                capture_output=True,
                text=True,
                check=False,
            )
        except OSError:
            return None
        out = done.stdout.strip()
        if done.returncode != 0 or not out:
            return None
        path = Path(out)
        return path if path.is_absolute() else (cfg.root / path).resolve()

    def stages(self, cfg: GhConfig) -> dict[str, str]:
        if not (cfg.root / CONFIG).is_file():
            return {}
        common = self.common_dir(cfg)
        if common is None:
            return {}
        return {stage: self._state(common / "hooks" / stage) for stage in STAGES}

    def problems(self, cfg: GhConfig) -> list[str]:
        found: list[str] = []
        for stage, state in self.stages(cfg).items():
            if state == "missing":
                found.append(
                    f"the pre-commit framework's {stage} hook is not installed — "
                    "run `vibey-gh setup`"
                )
            elif state == "foreign":
                found.append(
                    f"the {stage} hook in the git common directory is not the pre-commit "
                    "framework's, so its gates do not run — run `vibey-gh setup`"
                )
        return found

    @staticmethod
    def _state(hook: Path) -> str:
        if not hook.is_file():
            return "missing"
        try:
            head = hook.read_text(encoding="utf-8", errors="replace")[:_MARKER_WINDOW]
        except OSError:
            return "foreign"
        return "installed" if MARKER in head else "foreign"
